def parse_form(kind: str, form) -> dict:
    """Собирает данные конструктора из формы."""
    data: dict = {}
    for f in SCHEMAS[kind]["fields"]:
        k, t = f["key"], f["type"]
        if t in ("text", "textarea", "select"):
            data[k] = str(form.get(k, "")).strip()[:8000]
        elif t == "multi":
            data[k] = [v for v in form.getlist(k) if v in f["options"]]
        elif t == "list":
            data[k] = [str(v).strip()[:500] for v in form.getlist(k) if str(v).strip()]
        elif t == "steps":
            cols = len(f["columns"])
            cells = [str(v).strip()[:1000] for v in form.getlist(k)]
            rows = [cells[i:i + cols] for i in range(0, len(cells), cols)]
            data[k] = [r for r in rows if any(r)]
    return data
